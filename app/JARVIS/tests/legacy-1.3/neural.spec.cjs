const { test, expect } = require('@playwright/test');
const { installNeural } = require('./neural-fixture.cjs');
async function setup(page){await installNeural(page);await page.addInitScript(()=>{window.__TAURI_INTERNALS__={invoke:(command,args)=>{if(command==='get_system_metrics')return Promise.resolve({cpu_percent:0,ram_used_gb:2,ram_total_gb:8,os_name:'TEST OS',cpu_name:'TEST CPU'});if(command==='get_ai_status')return Promise.resolve({ready:true,provider:'Groq'});if(command==='voice_capabilities')return Promise.resolve({available:false,recognition:false,voices:[],note:'TEST no audio'});if(command==='voice_permission'||command==='voice_cancel')return Promise.resolve();return window.__neuralInvoke(command,args);}};});await page.goto('/');}
test('provider/model switching, safe key input, permission test and key deletion',async({page})=>{
 await setup(page);
 await page.getByLabel('KI-Anbieter',{exact:true}).selectOption('openai');
 await page.getByRole('button',{name:'Modelle beim Anbieter abrufen',exact:true}).click();
 await page.getByLabel('KI-Modell',{exact:true}).selectOption('test-new-live-model');
 expect(await page.evaluate(()=>window.__neuralTest.prefs.openai.model)).toBe('test-new-live-model');
 await page.getByRole('button',{name:'Neural Console',exact:true}).click();
 await page.getByLabel('Anbieter konfigurieren',{exact:true}).selectOption('openai');
 await page.getByLabel('Provider-Timeout',{exact:true}).fill('25');
 await page.getByLabel('Provider-Retries',{exact:true}).fill('1');
 await page.getByRole('button',{name:'Provider-Optionen speichern',exact:true}).click();
 expect(await page.evaluate(()=>window.__neuralTest.prefs.openai.timeout_seconds)).toBe(25);
 expect(await page.evaluate(()=>window.__neuralTest.prefs.openai.retries)).toBe(1);
 await page.getByLabel('Neuer API-Schlüssel',{exact:true}).fill('TEST_ONLY_NOT_A_CREDENTIAL');
 await page.getByRole('button',{name:'Sicher speichern / ersetzen',exact:true}).click();
 await expect(page.getByLabel('Neuer API-Schlüssel',{exact:true})).toHaveValue('');
 expect(await page.evaluate(()=>Object.keys(localStorage))).toEqual([]);
 await page.getByRole('button',{name:/Verbindung & Modell testen/}).click();
 await expect(page.getByText('HTTP 403: TEST Modellberechtigung fehlt.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Schlüssel löschen',exact:true}).click();
 expect(await page.evaluate(()=>window.__neuralTest.keys.openai)).toBe(false);
});
